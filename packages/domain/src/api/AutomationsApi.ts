/**
 * @since 0.0.0
 */
import * as HttpApiEndpoint from "effect/http-api/HttpApiEndpoint"
import * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as Schema from "effect/Schema"
import { Authentication } from "../Auth.ts"
import { Automation, AutomationDraft } from "../automations/Automation.ts"
import { AutomationCheck, EntryInfo } from "../automations/Catalog.ts"
import { AutomationDetail } from "../automations/Run.ts"
import { Conflict, InvalidAutomation, NotFound } from "../Errors.ts"
import { AgentId, AutomationId, RequestId } from "../Ids.ts"

/**
 * Automations: a trigger, conditions and an action, for one of your agents or your own trades. The catalog lists
 * every trigger, condition and action with its fields; `check` reads a draft back in sentences and says what can't
 * run; `defaults` gives the drafts an agent's template comes with, for the new agent's flow; `create` saves one
 * (once per request id); `update` pauses, resumes or edits it. Runs are on its detail.
 *
 * @stability unstable
 * @category groups
 * @since 0.0.0
 */
export class AutomationsApi extends HttpApiGroup.make("automations").add(
  HttpApiEndpoint.get("catalog", "/automations/catalog", {
    success: Schema.Array(EntryInfo)
  }),
  HttpApiEndpoint.get("list", "/automations", {
    query: { agentId: Schema.optionalKey(AgentId) },
    success: Schema.Array(Automation)
  }),
  HttpApiEndpoint.get("automation", "/automations/:id", {
    params: { id: AutomationId },
    success: AutomationDetail,
    error: NotFound
  }),
  HttpApiEndpoint.post("check", "/automations/check", {
    payload: Schema.Struct({ draft: AutomationDraft }),
    success: AutomationCheck,
    error: NotFound
  }),
  HttpApiEndpoint.get("defaults", "/agents/:agentId/automations/defaults", {
    params: { agentId: AgentId },
    /** The drafts its template comes with (none for a Stock picker or a custom agent), not saved. */
    success: Schema.Array(AutomationDraft),
    error: NotFound
  }),
  HttpApiEndpoint.post("create", "/automations", {
    payload: Schema.Struct({
      /** Generated by the client per automation, so a retried request saves it once. */
      requestId: RequestId,
      draft: AutomationDraft,
      /** `template` for one of the defaults its agent's template came with; `owner` when absent. */
      createdBy: Schema.optionalKey(Schema.Literals(["owner", "template"]))
    }),
    success: Automation,
    error: [InvalidAutomation, NotFound, Conflict]
  }),
  HttpApiEndpoint.patch("update", "/automations/:id", {
    params: { id: AutomationId },
    payload: Schema.Struct({
      /** Pause or resume it; absent to leave it as it is. */
      status: Schema.optionalKey(Schema.Literals(["active", "paused"])),
      /** Its new trigger, conditions, action and settings; its agent can't change. */
      draft: Schema.optionalKey(AutomationDraft)
    }),
    success: Automation,
    error: [InvalidAutomation, NotFound, Conflict]
  }),
  HttpApiEndpoint.delete("remove", "/automations/:id", {
    params: { id: AutomationId },
    success: Schema.Void,
    error: NotFound
  })
).middleware(Authentication) {}
