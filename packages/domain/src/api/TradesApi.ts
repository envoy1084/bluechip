/**
 * @since 0.0.0
 */
import * as HttpApiEndpoint from "effect/http-api/HttpApiEndpoint"
import * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as Schema from "effect/Schema"
import { Authentication } from "../Auth.ts"
import {
  Conflict,
  InsufficientCash,
  InsufficientShares,
  NotFound,
  NotTradable,
  PriceCheckFailed,
  QuoteUnavailable,
  SignatureRejected,
  Unavailable
} from "../Errors.ts"
import { RequestId, SigningRequestId, TradeId } from "../Ids.ts"
import { StockSymbol } from "../market/Market.ts"
import { Shares, Usdc } from "../market/Units.ts"
import { Trade, TradeRequest } from "../trading/Trade.ts"
import { AuthenticationCredential } from "../WebAuthn.ts"

/**
 * Buying and selling, in two steps: `prepare` quotes the trade, checks it against Chainlink and returns what the
 * passkey signs; `confirm` sends it. Its progress then arrives as `TradeUpdated` events.
 *
 * @stability unstable
 * @category groups
 * @since 0.0.0
 */
export class TradesApi extends HttpApiGroup.make("trades").add(
  HttpApiEndpoint.post("prepare", "/trades", {
    payload: Schema.Struct({
      /** Generated by the client per trade, so a retried request prepares it once. */
      requestId: RequestId,
      symbol: StockSymbol,
      side: Schema.Literals(["buy", "sell"]),
      /** Buy: the USDC to spend. Sell: the shares to sell. */
      amount: Schema.Union([Schema.Struct({ usdc: Usdc }), Schema.Struct({ shares: Shares })])
    }),
    success: TradeRequest,
    error: [
      InsufficientCash,
      InsufficientShares,
      NotTradable,
      QuoteUnavailable,
      PriceCheckFailed,
      Conflict,
      Unavailable
    ]
  }),
  HttpApiEndpoint.post("confirm", "/trades/:id/confirm", {
    params: { id: SigningRequestId },
    payload: Schema.Struct({ credential: AuthenticationCredential }),
    success: Trade,
    error: [NotFound, SignatureRejected, Unavailable]
  }),
  HttpApiEndpoint.get("trade", "/trades/:id", {
    params: { id: TradeId },
    success: Trade,
    error: NotFound
  })
).middleware(Authentication) {}
