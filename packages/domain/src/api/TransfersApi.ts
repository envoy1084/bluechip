/**
 * @since 0.0.0
 */
import * as HttpApiEndpoint from "effect/http-api/HttpApiEndpoint"
import * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as Schema from "effect/Schema"
import { Authentication } from "../Auth.ts"
import { Conflict, InsufficientCash, InvalidRequest, NotFound, SignatureRejected, Unavailable } from "../Errors.ts"
import { Address, RequestId, SigningRequestId } from "../Ids.ts"
import { Usdc } from "../market/Units.ts"
import { Page, PageQuery } from "../Page.ts"
import { SigningRequest, Transfer } from "../portfolio/Transfer.ts"
import { AuthenticationCredential } from "../WebAuthn.ts"

/**
 * Deposits and withdrawals. A withdrawal takes two steps: `prepare` returns what to sign, the browser signs it with
 * the passkey, `confirm` sends it. Its progress then arrives as `TransferUpdated` events.
 *
 * @stability unstable
 * @category groups
 * @since 0.0.0
 */
export class TransfersApi extends HttpApiGroup.make("transfers").add(
  HttpApiEndpoint.get("list", "/transfers", {
    query: PageQuery,
    success: Page(Transfer)
  }),
  HttpApiEndpoint.post("prepareWithdrawal", "/withdrawals", {
    payload: Schema.Struct({
      /** Generated by the client per withdrawal, so a retried request prepares it once. */
      requestId: RequestId,
      to: Address,
      amount: Usdc
    }),
    success: SigningRequest,
    error: [InsufficientCash, InvalidRequest, Conflict, Unavailable]
  }),
  HttpApiEndpoint.post("confirmWithdrawal", "/withdrawals/:id/confirm", {
    params: { id: SigningRequestId },
    payload: Schema.Struct({ credential: AuthenticationCredential }),
    success: Transfer,
    error: [NotFound, SignatureRejected, Unavailable]
  })
).middleware(Authentication) {}
