/**
 * @since 0.0.0
 */
import * as HttpApiEndpoint from "effect/http-api/HttpApiEndpoint"
import * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as Schema from "effect/Schema"
import { Agent, AgentName, AgentRequest, AgentUsage } from "../agents/Agent.ts"
import { Limits } from "../agents/Limits.ts"
import { Template } from "../agents/Templates.ts"
import { Authentication } from "../Auth.ts"
import { Conflict, InvalidLimits, NotFound, SignatureRejected, Unavailable } from "../Errors.ts"
import { AgentId, RequestId, SigningRequestId } from "../Ids.ts"
import { AuthenticationCredential } from "../WebAuthn.ts"

/**
 * Agents: creating one prepares its lock, changing its limits or removing it prepares the owner operation that does
 * it, and each is sent once the passkey signs it (`confirm`). Pausing is bluechip's alone and needs no signature.
 * Progress arrives as `AgentChanged` events.
 *
 * @stability unstable
 * @category groups
 * @since 0.0.0
 */
export class AgentsApi extends HttpApiGroup.make("agents").add(
  HttpApiEndpoint.get("list", "/agents", {
    success: Schema.Array(Agent)
  }),
  HttpApiEndpoint.get("agent", "/agents/:id", {
    params: { id: AgentId },
    success: Agent,
    error: NotFound
  }),
  HttpApiEndpoint.get("usage", "/agents/:id/usage", {
    params: { id: AgentId },
    success: AgentUsage,
    error: [NotFound, Unavailable]
  }),
  HttpApiEndpoint.post("create", "/agents", {
    payload: Schema.Struct({
      /** Generated by the client per agent, so a retried request creates it once. */
      requestId: RequestId,
      name: AgentName,
      template: Template,
      limits: Limits
    }),
    success: AgentRequest,
    error: [InvalidLimits, NotFound, Conflict, Unavailable]
  }),
  HttpApiEndpoint.post("lock", "/agents/:id/lock", {
    params: { id: AgentId },
    payload: Schema.Struct({ requestId: RequestId }),
    success: AgentRequest,
    error: [NotFound, Conflict, Unavailable]
  }),
  HttpApiEndpoint.post("changeLimits", "/agents/:id/limits", {
    params: { id: AgentId },
    payload: Schema.Struct({ requestId: RequestId, limits: Limits }),
    success: AgentRequest,
    error: [InvalidLimits, NotFound, Conflict, Unavailable]
  }),
  HttpApiEndpoint.post("remove", "/agents/:id/remove", {
    params: { id: AgentId },
    payload: Schema.Struct({ requestId: RequestId }),
    /** A draft is removed at once (nothing onchain); a locked agent's session is revoked once you sign. */
    success: Schema.Union([Agent, AgentRequest]),
    error: [NotFound, Conflict, Unavailable]
  }),
  HttpApiEndpoint.post("confirm", "/agents/requests/:id/confirm", {
    params: { id: SigningRequestId },
    payload: Schema.Struct({ credential: AuthenticationCredential }),
    success: Agent,
    error: [NotFound, Conflict, SignatureRejected, Unavailable]
  }),
  HttpApiEndpoint.post("pause", "/agents/:id/pause", {
    params: { id: AgentId },
    success: Agent,
    error: [NotFound, Conflict]
  }),
  HttpApiEndpoint.post("resume", "/agents/:id/resume", {
    params: { id: AgentId },
    success: Agent,
    error: [NotFound, Conflict]
  }),
  HttpApiEndpoint.post("pauseAll", "/agents/pause-all", {
    success: Schema.Array(Agent)
  }),
  HttpApiEndpoint.post("resumeAll", "/agents/resume-all", {
    success: Schema.Array(Agent)
  })
).middleware(Authentication) {}
