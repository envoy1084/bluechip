/**
 * @since 0.0.0
 */
import * as HttpApiEndpoint from "effect/http-api/HttpApiEndpoint"
import * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as Schema from "effect/Schema"
import { Authentication } from "../Auth.ts"
import {
  Conflict,
  InsufficientCash,
  InsufficientShares,
  NotFound,
  NotTradable,
  PriceCheckFailed,
  QuoteUnavailable,
  SignatureRejected,
  Unavailable
} from "../Errors.ts"
import { AgentId, IntentId, RequestId, SigningRequestId } from "../Ids.ts"
import { Decision, Intent, IntentRequest, IntentSource, IntentStatus, Leg } from "../intents/Intent.ts"
import { Page, PageQuery } from "../Page.ts"
import { AuthenticationCredential } from "../WebAuthn.ts"

const TradeErrors = [
  InsufficientCash,
  InsufficientShares,
  NotTradable,
  QuoteUnavailable,
  PriceCheckFailed,
  NotFound,
  Conflict,
  Unavailable
] as const

/**
 * Intents: every trade, yours or an agent's. Trading through an agent creates an intent its policies decide (follow
 * it with `IntentChanged`); trading yourself, or approving an agent's trade, prepares it for your passkey
 * (`confirm`). `preview` says what would happen without trading.
 *
 * @stability unstable
 * @category groups
 * @since 0.0.0
 */
export class IntentsApi extends HttpApiGroup.make("intents").add(
  HttpApiEndpoint.post("preview", "/intents/preview", {
    payload: Schema.Struct({ agentId: AgentId, leg: Leg }),
    success: Decision,
    error: TradeErrors
  }),
  HttpApiEndpoint.post("create", "/intents", {
    payload: Schema.Struct({
      /** Generated by the client per trade, so a retried request creates it once. */
      requestId: RequestId,
      /** The agent to trade through; `null` to trade yourself. */
      agentId: Schema.NullOr(AgentId),
      leg: Leg,
      reason: Schema.optionalKey(Schema.String)
    }),
    /** Through an agent: the intent, decided in the background. Yourself: the request for your passkey. */
    success: Schema.Union([Intent, IntentRequest]),
    error: TradeErrors
  }),
  HttpApiEndpoint.get("list", "/intents", {
    query: {
      ...PageQuery,
      agentId: Schema.optionalKey(AgentId),
      status: Schema.optionalKey(IntentStatus),
      source: Schema.optionalKey(IntentSource)
    },
    success: Page(Intent)
  }),
  HttpApiEndpoint.get("intent", "/intents/:id", {
    params: { id: IntentId },
    success: Intent,
    error: NotFound
  }),
  HttpApiEndpoint.get("approvals", "/approvals", {
    success: Schema.Array(Intent)
  }),
  HttpApiEndpoint.post("approve", "/intents/:id/approve", {
    params: { id: IntentId },
    payload: Schema.Struct({ requestId: RequestId }),
    success: IntentRequest,
    error: TradeErrors
  }),
  HttpApiEndpoint.post("confirm", "/intents/requests/:id/confirm", {
    params: { id: SigningRequestId },
    payload: Schema.Struct({ credential: AuthenticationCredential }),
    success: Intent,
    error: [NotFound, Conflict, SignatureRejected, Unavailable]
  }),
  HttpApiEndpoint.post("decline", "/intents/:id/decline", {
    params: { id: IntentId },
    success: Intent,
    error: [NotFound, Conflict]
  }),
  HttpApiEndpoint.post("cancel", "/intents/:id/cancel", {
    params: { id: IntentId },
    success: Intent,
    error: [NotFound, Conflict]
  })
).middleware(Authentication) {}
